#!/usr/bin/env python3
"""Layer check for src/: a file may include headers of its own layer or lower.

Layers, low to high: core < grid < sim < presentation < app (directories per layer in LAYERS below).
Existing violations are recorded in tools/layers_baseline.txt; only new ones fail.

  python3 tools/check_layers.py            check against the baseline (exit 1 on new violations)
  python3 tools/check_layers.py --update   rewrite the baseline from the current tree
  python3 tools/check_layers.py --summary  print violation counts per (layer -> layer)
"""

import argparse
import collections
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')
BASELINE = os.path.join(ROOT, 'tools', 'layers_baseline.txt')

LAYERS = [
    ('core', ['core', 'events']),
    ('grid', ['grid']),
    ('sim', ['building', 'figure', 'figuretype', 'city', 'scenario', 'empire', 'game', 'io', 'resource', 'config']),
    ('presentation', ['graphics', 'overlays', 'widget', 'window', 'sound', 'input', 'content']),
    ('app', ['platform', 'js', 'dev', 'debug', 'editor', 'net']),
]

# Enum-only "vocabulary" headers: usable from any layer as long as they include nothing above themselves.
VOCABULARY = {
    'building/building_type.h',
    'city/constants.h',
    'figure/figure_type.h',
    'game/resource.h',
}

# Low-level infrastructure that sits in a higher directory: treated as core when included.
# Moving these files where they belong is part of the plan; until then they are not violations.
INFRASTRUCTURE = {
    'js/js.h',
    'js/js_defines.h',
    'js/js_events.h',
    'js/js_game.h',
    'js/js_struct.h',
    'io/io_buffer.h',
    'platform/platform.h',
    'content/vfs.h',
}

IGNORED_DIRS = {'mujs', 'lame', 'bzip', 'lzma', 'scripts'}

INCLUDE_RE = re.compile(r'^\s*#\s*include\s+"([^"]+)"', re.M)

RANK = {d: i for i, (_, dirs) in enumerate(LAYERS) for d in dirs}
LAYER_NAME = {d: name for name, dirs in LAYERS for d in dirs}


def top_dir(rel):
    return rel.split('/', 1)[0]


def is_exempt_source(rel):
    # JS binding glue lives next to the code it binds; it is checked by its own rule later.
    return re.search(r'_js\.(cpp|h)$', rel) is not None


def resolve(src_rel, inc):
    if '/' in inc and top_dir(inc) in RANK or top_dir(inc) in IGNORED_DIRS:
        return inc
    local = os.path.normpath(os.path.join(os.path.dirname(src_rel), inc)).replace(os.sep, '/')
    if os.path.exists(os.path.join(SRC, local)):
        return local
    return inc


def collect():
    violations = set()
    for dirpath, dirnames, filenames in os.walk(SRC):
        rel_dir = os.path.relpath(dirpath, SRC).replace(os.sep, '/')
        if top_dir(rel_dir) in IGNORED_DIRS:
            dirnames[:] = []
            continue
        for fn in filenames:
            if not fn.endswith(('.cpp', '.h', '.hpp')):
                continue
            rel = fn if rel_dir == '.' else rel_dir + '/' + fn
            src_layer = top_dir(rel)
            if src_layer not in RANK or is_exempt_source(rel):
                continue
            text = open(os.path.join(SRC, rel), encoding='utf-8', errors='replace').read()
            for inc in INCLUDE_RE.findall(text):
                target = resolve(rel, inc)
                tgt_layer = top_dir(target)
                if tgt_layer not in RANK or target in VOCABULARY or target in INFRASTRUCTURE or target.endswith('_fwd.h'):
                    continue
                if RANK[tgt_layer] > RANK[src_layer]:
                    violations.add('%s -> %s' % (rel, target))
    return violations


def read_baseline():
    if not os.path.exists(BASELINE):
        return set()
    lines = open(BASELINE, encoding='utf-8').read().splitlines()
    return {l.strip() for l in lines if l.strip() and not l.startswith('#')}


def write_baseline(violations):
    with open(BASELINE, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# Known layer violations (file -> included header). Generated by tools/check_layers.py --update.\n')
        f.write('# Remove lines as violations get fixed; never add lines by hand to silence a new one.\n')
        for v in sorted(violations):
            f.write(v + '\n')


def summary(violations):
    pairs = collections.Counter()
    for v in violations:
        src, tgt = v.split(' -> ')
        pairs[(LAYER_NAME[top_dir(src)], top_dir(src), top_dir(tgt))] += 1
    for (layer, s, t), n in sorted(pairs.items(), key=lambda x: (-x[1])):
        print('%5d  %-10s %-12s -> %s' % (n, layer, s, t))
    print('%5d  total' % len(violations))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--update', action='store_true')
    ap.add_argument('--summary', action='store_true')
    args = ap.parse_args()

    current = collect()
    if args.summary:
        summary(current)
        return 0
    if args.update:
        write_baseline(current)
        print('baseline updated: %d violations' % len(current))
        return 0

    baseline = read_baseline()
    new = sorted(current - baseline)
    fixed = sorted(baseline - current)
    if fixed:
        print('%d baseline entries are fixed; remove them (or run --update):' % len(fixed))
        for v in fixed:
            print('  ' + v)
    if new:
        print('%d new layer violations (a file includes a header from a higher layer):' % len(new))
        for v in new:
            print('  ' + v)
        print('Layers, low to high: ' + ' < '.join(name for name, _ in LAYERS))
        return 1
    print('layer check passed: %d known violations, 0 new' % len(current))
    return 0


if __name__ == '__main__':
    sys.exit(main())
